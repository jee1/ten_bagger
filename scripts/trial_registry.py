"""Render docs/architecture/trial-registry.md from committed run artifacts.

Every calibration and walk-forward run is a trial. The registry keeps the count
honest for multiple-testing corrections, so it lists failed and exploratory runs too.

Usage: python trial_registry.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "docs" / "architecture" / "trial-registry.md"

NOTES = {
    "d9a711990b5fe529": (
        "Do not cite the 0.40 H20 mean. A 10x entry-price error on 002780.KS inflated it "
        "(see price-basis-validation-002780.md)."
    ),
    "72d35b76ef94d934": "Child of d9a711990b5fe529. Same 002780.KS caveat.",
}


def _load(directory: str) -> list[dict]:
    return [
        json.loads(p.read_text()) for p in sorted((ROOT / "content" / directory).glob("*.json"))
    ]


def _cell(value: object) -> str:
    return "" if value is None else str(value)


def render() -> str:
    calibration = sorted(_load("calibration"), key=lambda r: (r["generatedAt"], r["runId"]))
    walk_forward = sorted(_load("walk-forward"), key=lambda r: (r["generatedAt"], r["runId"]))

    lines = [
        "# Trial registry",
        "",
        "Generated by `scripts/trial_registry.py`. Do not edit by hand.",
        "CI fails when this file drifts from `content/calibration/` and `content/walk-forward/`.",
        "",
        f"Calibration packages: {len(calibration)}. Walk-forward runs: {len(walk_forward)}.",
        "",
        "## Calibration packages",
        "",
        "| runId | generatedAt | intent | mode | verdict | failed bullets | note |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in calibration:
        lines.append(
            f"| `{r['runId']}` | {r['generatedAt'][:10]} | {r['packageIntent']} | {r['mode']} "
            f"| {r['overallVerdict']} | {', '.join(r.get('failedBullets') or [])} "
            f"| {NOTES.get(r['runId'], '')} |"
        )
    lines += [
        "",
        "## Walk-forward runs",
        "",
        "| runId | generatedAt | intent | candidate | window | OOS pick days | note |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in walk_forward:
        spec = r["foldSpec"]
        lines.append(
            f"| `{r['runId']}` | {r['generatedAt'][:10]} | {r['runIntent']} | {r['candidateId']} "
            f"| {spec['startDate']}..{spec['endDate']} "
            f"| {_cell((r.get('coverage') or {}).get('oosPickDays'))} "
            f"| {NOTES.get(r['runId'], '')} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not REGISTRY_PATH.exists() or REGISTRY_PATH.read_text() != text:
            print("trial-registry.md is stale. Run: cd scripts && python trial_registry.py")
            return 1
        return 0
    REGISTRY_PATH.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
